test("unauthorized users see no quick-create plus controls on the OL wizard", async ({ page }) => {
  await seedSuperuserSession(page)
  await mockAccessApi(page, undefined, [])
  await mockDropdownQuickCreateApi(page)

  await page.goto("/ordinary-life/quotations/new")
  await expect(page.getByRole("heading", { name: "Personal Details" })).toBeVisible()
  for (const entityLabel of ["Identity Type", "Location", "Agent"]) {
    await expect(page.getByRole("button", { name: `Add new ${entityLabel}` })).toHaveCount(0)
  }
  await page.getByRole("button", { name: "Plan & Sub-Products" }).click()
  await expect(page.getByRole("button", { name: "Add product" })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Add new Payment Frequency" })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Add new Quote Basis" })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Add new Premium Factor" })).toHaveCount(0)
})
