import { expect, test, type Page } from "@playwright/test"
import { mockAccessApi, mockDropdownQuickCreateApi, seedSuperuserSession } from "./fixtures"

const UUID_PATTERN = /\b[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\b/i

async function expectNoVisibleUuid(page: Page) {
  const bodyText = await page.locator("body").innerText()
  expect(bodyText).not.toMatch(UUID_PATTERN)
}

async function createOption(page: Page, entityLabel: string, code: string, name: string, configure?: (dialog: ReturnType<Page["getByRole"]>) => Promise<void>) {
  await page.getByRole("button", { name: `Add new ${entityLabel}` }).click()
  const dialog = page.getByRole("dialog").filter({ has: page.getByRole("heading", { name: `Add ${entityLabel}`, exact: true }) }).last()
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole("heading", { name: `Add ${entityLabel}` })).toBeVisible()
  await dialog.getByLabel(/Code/).fill(code)
  await dialog.getByLabel(/Name/).fill(name)
  if (configure) await configure(dialog)
  await dialog.getByRole("button", { name: "Create option" }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText(name, { exact: true }).last()).toBeVisible()
}

async function createNestedOption(page: Page, parentEntityLabel: string, nestedEntityLabel: string, parentCode: string, parentName: string, nestedCode: string, nestedName: string, configureParent?: (dialog: ReturnType<Page["getByRole"]>) => Promise<void>) {
  await page.getByRole("button", { name: `Add new ${parentEntityLabel}` }).click()
  const parentDialog = page.getByRole("dialog").filter({ has: page.getByRole("heading", { name: `Add ${parentEntityLabel}`, exact: true }) }).last()
  await expect(parentDialog).toBeVisible()
  await parentDialog.getByLabel(/Code/).fill(parentCode)
  await parentDialog.getByLabel(/Name/).fill(parentName)
  await parentDialog.getByRole("button", { name: `Add new ${nestedEntityLabel}` }).click()
  const nestedDialog = page.getByRole("dialog").filter({ has: page.getByRole("heading", { name: `Add ${nestedEntityLabel}`, exact: true }) }).last()
  await expect(nestedDialog).toBeVisible()
  await nestedDialog.getByLabel(/Code/).fill(nestedCode)
  await nestedDialog.getByLabel(/Name/).fill(nestedName)
  await nestedDialog.getByRole("button", { name: "Create option" }).click()
  await expect(nestedDialog).toBeHidden()
  if (configureParent) await configureParent(parentDialog)
  await parentDialog.getByRole("button", { name: "Create option" }).click()
  await expect(parentDialog).toBeHidden()
  await expect(page.getByText(parentName, { exact: true }).last()).toBeVisible()
}

