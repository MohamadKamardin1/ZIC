import { useEffect, useState } from "react"
import { Loader2 } from "lucide-react"
import { PageHeader } from "./SharedComponents"
import { resolveGroupId } from "../../lib/api"
import ParameterCrud from "./ParameterCrud"

export default function ReinsuranceParameters() {
  const [groupId, setGroupId] = useState<string | null>(null)
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    resolveGroupId("REINSURANCE")
      .then(setGroupId)
      .finally(() => setLoading(false))
  }, [])

  if (loading) {
    return (
      <div className="flex items-center justify-center py-12 text-muted-foreground">
        <Loader2 className="mr-2 h-5 w-5 animate-spin" />
        Loading...
      </div>
    )
  }

  if (!groupId) {
    return (
      <div>
        <PageHeader title="Reinsurance Parameters" description="Reinsurance treaties, limits, and cession rules" />
        <p className="text-sm text-muted-foreground">Parameter group not found. Run data migration.</p>
      </div>
    )
  }

  return (
    <div>
      <PageHeader title="Reinsurance Parameters" description="Reinsurance treaties, limits, and cession rules" />
      <ParameterCrud
        groupId={groupId}
        title="Reinsurance Configuration"
        description="Treaty types, cession percentages, facultative thresholds, retention limits, and other reinsurance settings."
      />
    </div>
  )
}
